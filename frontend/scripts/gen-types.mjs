// Generates src/data/types.gen.ts from ../schema/*.schema.json (single source of truth).
// Usage: npm run gen:types
import { compileFromFile } from 'json-schema-to-typescript';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, '../../schema');
const names = ['index', 'analysis', 'map', 'frames', 'compare', 'catalog', 'validation', 'series-index'];
let out = '/* Generated by scripts/gen-types.mjs from schema/*.schema.json. Do not edit by hand. */\n\n';
const seen = new Set();
for (const n of names) {
  const ts = await compileFromFile(path.join(schemaDir, `${n}.schema.json`), {
    cwd: schemaDir,
    bannerComment: '',
    declareExternallyReferenced: true,
    additionalProperties: false,
    style: { singleQuote: true },
  });
  // drop duplicate declarations of shared definitions
  const blocks = ts.split(/\n(?=export )/);
  for (const b of blocks) {
    const m = b.match(/^export (?:interface|type) (\w+)/);
    if (m && seen.has(m[1])) continue;
    if (m) seen.add(m[1]);
    out += b.trim() + '\n\n';
  }
}
writeFileSync(path.join(here, '../src/data/types.gen.ts'), out);
console.log('wrote src/data/types.gen.ts');
